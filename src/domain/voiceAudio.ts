/** Wire format for one minute of mono signed 16-bit PCM speech, wrapped in WAV. */
export const VOICE_SECONDS = 60;
export const VOICE_SAMPLE_RATE = 16_000;
const HEADER = 44;
export const MAX_VOICE_BYTES = HEADER + VOICE_SECONDS * VOICE_SAMPLE_RATE * 2;

/** Normalize microphone PCM to a simple format all deployed Gemini models can read. */
export function voiceWav(samples: Float32Array): ArrayBuffer {
  const count = Math.min(samples.length, VOICE_SECONDS * VOICE_SAMPLE_RATE);
  const data = new ArrayBuffer(HEADER + count * 2);
  const view = new DataView(data);
  const bytes = new Uint8Array(data);
  bytes.set([82, 73, 70, 70], 0); // RIFF
  view.setUint32(4, bytes.length - 8, true);
  bytes.set([87, 65, 86, 69, 102, 109, 116, 32], 8); // WAVEfmt
  view.setUint32(16, 16, true);
  view.setUint16(20, 1, true); // PCM
  view.setUint16(22, 1, true); // mono
  view.setUint32(24, VOICE_SAMPLE_RATE, true);
  view.setUint32(28, VOICE_SAMPLE_RATE * 2, true);
  view.setUint16(32, 2, true);
  view.setUint16(34, 16, true);
  bytes.set([100, 97, 116, 97], 36); // data
  view.setUint32(40, count * 2, true);
  for (let i = 0; i < count; i++) {
    const sample = Math.min(1, Math.max(-1, samples[i]));
    view.setInt16(HEADER + i * 2, Math.round(sample * (sample < 0 ? 32768 : 32767)), true);
  }
  return data;
}

/** Accept only the bounded PCM layout generated by our recorder. Duration follows from the data length. */
export function validVoiceWav(bytes: Uint8Array): boolean {
  if (bytes.length < HEADER + 2 || bytes.length > MAX_VOICE_BYTES || bytes.length % 2 !== 0) return false;
  const v = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
  return v.getUint32(0) === 0x52494646 && v.getUint32(4, true) === bytes.length - 8 && v.getUint32(8) === 0x57415645 &&
    v.getUint32(12) === 0x666d7420 && v.getUint32(16, true) === 16 && v.getUint16(20, true) === 1 && v.getUint16(22, true) === 1 &&
    v.getUint32(24, true) === VOICE_SAMPLE_RATE && v.getUint32(28, true) === VOICE_SAMPLE_RATE * 2 &&
    v.getUint16(32, true) === 2 && v.getUint16(34, true) === 16 && v.getUint32(36) === 0x64617461 && v.getUint32(40, true) === bytes.length - HEADER;
}
